# 1. 약수를 구하는 방법에 대해 생각 
# 약수란 나누어 떨어지는 것이 0이 되는 것 -> % == 0를 사용 해야 한다. 
# 여태껏 약수를 구할 때 2로 나누어서 구하였지만, 그건 나누는 값(i)를 계속 변동하기에 가능 
