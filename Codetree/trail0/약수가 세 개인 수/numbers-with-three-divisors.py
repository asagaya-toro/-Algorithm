# 문제: 약수가 세 개인 수
# 입력 : 정수 start, end
# 출력 : 정수의 약수가 3개인 수의 개수 
# 날짜: 2026/6/18 ~ 20 (토)
# 난이도 : 쉬움 | 소요시간: 43 분
# 접근 : for문으로 start ~ end 까지 돌리고, 
# 약수 구하고 , if문으로 약수의 개수가 3개면, 3개인 수의 개수를 더해서 출력 

# 입력 
start, end = map(int, input().split())
result = 0

# start ~ end 까지 반복 
for i in range(start, end+1) : 
    cnt = 0
    for j in range(1, i+1) :
        if i % j == 0 :
            cnt +=1
    if cnt == 3 : 
        result += 1

print(result)

